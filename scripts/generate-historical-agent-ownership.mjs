#!/usr/bin/env node
/**
 * Regenerate src/installer/historical-agent-ownership.ts from THIS fork's
 * release tags.
 *
 * The inventory authorizes the installer to reclaim standalone agent files it
 * previously shipped. Records are exact: filename + byte length + SHA-256.
 * Anything not matching is treated as user-authored and left alone.
 *
 * The upstream file this replaces was generated from upstream's own v4 tags and
 * upstream's file bytes, so every fork-installed agent failed authentication and
 * would never be reclaimed on upgrade. This regenerates the same shape from the
 * fork's tags, where the agent files are named `<name>.agent.md`.
 *
 * Usage:  node scripts/generate-historical-agent-ownership.mjs [--verify]
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/installer/historical-agent-ownership.ts');
const TAG_RE = /^v4\.\d+\.\d+$/;

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function gitBuffer(args) {
  return execFileSync('git', args, { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 });
}

/** Fork release tags, oldest first. */
function forkTags() {
  return git(['tag', '-l', '--merged', 'origin/dev'])
    .split('\n')
    .map((t) => t.trim())
    .filter((t) => TAG_RE.test(t))
    .sort((a, b) => {
      const pa = a.slice(1).split('.').map(Number);
      const pb = b.slice(1).split('.').map(Number);
      return pa[0] - pb[0] || pa[1] - pb[1] || pa[2] - pb[2];
    });
}

/** Safe = top-level agents/<name>.agent.md or agents/<name>.md, no nesting. */
function isSafeAgentPath(path) {
  return /^agents\/[A-Za-z0-9._-]+\.(agent\.)?md$/.test(path) && !path.endsWith('/AGENTS.md');
}

function collect() {
  // key -> record, keyed by filename+sha so identical bytes across tags collapse
  // into one record with a first/last release range.
  const records = new Map();

  for (const tag of forkTags()) {
    let listing;
    try {
      listing = git(['ls-tree', '-r', '--format=%(objectname) %(path)', tag, 'agents/']);
    } catch {
      continue; // tag lacks an agents/ tree
    }

    for (const line of listing.split('\n')) {
      if (!line.trim()) continue;
      const sp = line.indexOf(' ');
      const blob = line.slice(0, sp);
      const path = line.slice(sp + 1);
      if (!isSafeAgentPath(path)) continue;

      const filename = path.slice('agents/'.length);
      if (filename === 'AGENTS.md') continue;

      const content = gitBuffer(['cat-file', 'blob', blob]);
      const sha256 = createHash('sha256').update(content).digest('hex');
      const key = `${filename}:${sha256}`;

      const existing = records.get(key);
      if (existing) {
        existing.lastReleaseTag = tag;
      } else {
        records.set(key, {
          filename,
          byteLength: content.length,
          sha256,
          gitBlob: blob,
          firstReleaseTag: tag,
          lastReleaseTag: tag,
        });
      }
    }
  }

  return [...records.values()].sort(
    (a, b) => a.filename.localeCompare(b.filename) || a.firstReleaseTag.localeCompare(b.firstReleaseTag),
  );
}

function render(records) {
  const lines = records.map(
    (r) =>
      `  { filename: ${JSON.stringify(r.filename)}, byteLength: ${r.byteLength}, sha256: '${r.sha256}', gitBlob: '${r.gitBlob}', firstReleaseTag: '${r.firstReleaseTag}', lastReleaseTag: '${r.lastReleaseTag}' },`,
  );

  return `/**
 * Exact ownership records for standalone agent files shipped by this fork's
 * v4 release tags.
 *
 * GENERATED by scripts/generate-historical-agent-ownership.mjs -- do not edit by
 * hand. Regenerate after cutting a release that changes agents/.
 *
 * A record authorizes only the exact filename, byte length, and SHA-256 bytes;
 * release tags and the git blob provide audit provenance. Files that do not
 * match exactly are treated as user-authored and are never reclaimed.
 *
 * Do not replace this with filename, frontmatter, or fuzzy ownership heuristics.
 */

export interface HistoricalAgentOwnership {
  filename: string;
  byteLength: number;
  sha256: string;
  gitBlob: string;
  firstReleaseTag: string;
  lastReleaseTag: string;
}

export const HISTORICAL_AGENT_OWNERSHIP: readonly HistoricalAgentOwnership[] = [
${lines.join('\n')}
];
`;
}

const records = collect();
const output = render(records);

if (process.argv.includes('--verify')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== output) {
    console.error(`[historical-agent-ownership] out of date -- run: node scripts/generate-historical-agent-ownership.mjs`);
    process.exit(1);
  }
  console.log(`historical agent ownership current (${records.length} records)`);
} else {
  writeFileSync(OUT, output, 'utf8');
  console.log(`wrote ${records.length} ownership records to src/installer/historical-agent-ownership.ts`);
}
